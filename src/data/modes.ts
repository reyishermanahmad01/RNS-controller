export function getWhiteModeSubgroup(mode: RgbMode): WhiteSubGroup {
  if (mode.pattern.startsWith('white-run-')) return 'White Running';
  if (mode.pattern.startsWith('white-strobe-')) return 'White Strobo';
  return 'White Matrix';
}

const BASE_COUNT = 380;

// 43 genuinely distinct patterns x 9 color themes (380 base modes) + 20 White Full modes = 400 RNS modes
export const RGB_MODES: RgbMode[] = [
  ...Array.from({ length: BASE_COUNT }, (_, index) => {
    const id = index + 1;
    const themeIdx = Math.floor(index / PATTERN_TEMPLATES.length) % COLOR_THEMES.length;
    const patternIdx = index % PATTERN_TEMPLATES.length;
    const tpl = PATTERN_TEMPLATES[patternIdx];
    const theme = COLOR_THEMES[themeIdx];

    return {
      id,
      code: `Mode ${String(id).padStart(3, '0')}`,
      name: `${tpl.baseName} · ${theme.label}`,
      category: tpl.category,
      description: tpl.description,
      primaryColor: theme.primary,
      secondaryColor: theme.secondary,
      pattern: tpl.pattern,
    };
  }),
  ...WHITE_SPECIAL_MODES,
];

